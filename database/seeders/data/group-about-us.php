Our Mission
To bring the objects in ROM’s arts, culture and nature collections to life for visitors through various enchanting tours. These include free scheduled tours daily and regular paid tours in ROM’s many exceptional permanent galleries and temporary Special Exhibitions.

What We Do
The Docents are highly dedicated and enthusiastic ROM volunteers giving a variety of museum tours to engaged and appreciative visitors to ROM. These tours include five free scheduled tours daily and numerous paid tours. Through highlights, gallery tours, and themed journeys, visitors explore ROM’s collections, discovering iconic objects that bridge time, space and cultures. Docents also give tours for some temporary and visiting Special Exhibitions at the Museum.

Materials for docent-led tours are vetted by Curatorial staff. In addition, Docents are required to have a good general knowledge of the Museum and its collections as well as on-going Special Exhibitions. Docent-led tours are vetted by peers every other year. Apart from giving a minimum of 25 tours a year, Docents are also required to undertake administrative jobs on a regular basis. Such participation is necessary to maintain the Committee’s cherished freedom of being self-administering.

The Docent Committee holds 7 general meetings annually with the first hour of each meeting focusing on business matters followed by an education component in the second hour. Guest speakers are usually from ROM Curatorial and Staff who keep the Docent Committee current on ROM research and other developments in the Museum.

The Docent Committee functions comfortably with 50 to 60 active Docents. Training programs need to be held when the numbers fall below 40. To ensure that ROM`s high standards are met, the Docent Training Program is rigorous, including both content and delivery style. The training takes about 15 weeks to complete.

How to Join
The Docent Committee welcomes fellow volunteers from all DMV committees with a minimum one year of service, preferably in the Museum Interpretation Section, to join an intensive 15-week Docent Training Program which is usually held every other year. The Docent Committee will reach out to other DMV committees on any upcoming Docent Training Program and invite interested volunteers to apply. Interviews are held and successful candidates notified several weeks before the training course starts.

Please feel free to reach out to the Docent Executive team if you have any questions.

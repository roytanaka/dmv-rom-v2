About the Bishop White Committee: Friends of East Asia

Who was Bishop White?

The committee is named for Bishop William White, a Canadian missionary working in China in the early 20th century who also acted on behalf of the ROM, acquiring objects of significance and beauty for the Museum and helping to create interest in Chinese art and culture. Upon his return to Toronto in 1935, he was appointed first Keeper of the East Asiatic Collections at the ROM. The Bishop White Committee was founded in 1960 by his student, Louise Hawley Stone, to honour his memory and to continue his legacy.

Since its inception, the Bishop White Committee has donated more than $2.5 million to the ROM for the promotion of East Asian art, history and culture. It has endowed curatorships, supported the Library of East Asia and funded research and conservation projects.

The Committee sponsors speaker programs and curatorial grants, and supports the ROM’s expanding Chinese, Japanese and Korean collections.

If you are interested in East Asian art and culture (China, Japan and Korea), and would like to join this active and hard-working group, please contact the Co-Chairs.
